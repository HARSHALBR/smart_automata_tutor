/**
 * Context-Free Grammar Ambiguity Analysis Engine:
 * - Exhaustive bounded search for ambiguity witness strings
 * - Custom user string ambiguity testing
 * - Extraction of two distinct parse trees and distinct leftmost derivations
 * - Honest theoretical disclaimer highlighting that general CFG ambiguity is undecidable (PCP reduction)
 */

import {
  type Grammar,
  type ParseNode,
  findAllParseTrees,
  treeToLeftmostDerivation,
  type DerivationStep,
  tokenizeInputString,
} from './cfg'

export interface AmbiguityWitness {
  string: string
  tree1: ParseNode
  tree2: ParseNode
  derivation1: DerivationStep[]
  derivation2: DerivationStep[]
  divergenceStepIndex: number
}

export interface AmbiguityAnalysisResult {
  isAmbiguous: boolean
  evaluatedString?: string
  witness?: AmbiguityWitness
  testedStringsCount: number
  maxTestedLength: number
  inconclusive: boolean
  explanation: string
  undecidabilityDisclaimer: string
}

const UNDECIDABILITY_DISCLAIMER =
  'Theoretical Note: Determining whether an arbitrary Context-Free Grammar is ambiguous is ' +
  'undecidable in the general case (proved via reduction from Post’s Correspondence Problem, PCP). ' +
  'Finding a string with two distinct parse trees mathematically proves ambiguity; however, ' +
  'finding no ambiguous strings within a bounded search does NOT prove the grammar is unambiguous.';

/**
 * Generates all strings over terminals up to a maximum length.
 */
function* generateStringsUpToLength(terminals: string[], maxLen: number): Generator<string> {
  const terms = terminals.filter((t) => t.length > 0 && t !== 'ε')
  if (terms.length === 0) {
    yield ''
    return
  }

  yield ''
  let currentLengthStrings = ['']

  for (let len = 1; len <= maxLen; len++) {
    const nextLengthStrings: string[] = []
    for (const prefix of currentLengthStrings) {
      for (const t of terms) {
        const nextStr = prefix + t
        nextLengthStrings.push(nextStr)
        yield nextStr
      }
    }
    currentLengthStrings = nextLengthStrings
    // Cap exponential expansion to prevent browser freeze
    if (currentLengthStrings.length > 500) break
  }
}

/**
 * Finds the index of the first derivation step where two derivations diverge.
 */
function findDivergenceStep(d1: DerivationStep[], d2: DerivationStep[]): number {
  const minLen = Math.min(d1.length, d2.length)
  for (let i = 0; i < minLen; i++) {
    if (d1[i].production !== d2[i].production || d1[i].expanded !== d2[i].expanded) {
      return i
    }
  }
  return minLen
}

/**
 * Analyzes whether a grammar is ambiguous:
 * 1. If targetString is provided, tests that specific string.
 * 2. If no string is provided, runs a bounded search across short strings in Σ*.
 */
export function analyzeAmbiguity(
  grammar: Grammar,
  targetString?: string,
  maxLen: number = 5,
): AmbiguityAnalysisResult {
  // Case A: User supplied a target string to verify
  if (targetString !== undefined) {
    const trees = findAllParseTrees(grammar, targetString, 2)
    if (trees.length >= 2) {
      const d1 = treeToLeftmostDerivation(trees[0], grammar.start)
      const d2 = treeToLeftmostDerivation(trees[1], grammar.start)
      const divIdx = findDivergenceStep(d1, d2)

      const witness: AmbiguityWitness = {
        string: targetString,
        tree1: trees[0],
        tree2: trees[1],
        derivation1: d1,
        derivation2: d2,
        divergenceStepIndex: divIdx,
      }

      return {
        isAmbiguous: true,
        evaluatedString: targetString,
        witness,
        testedStringsCount: 1,
        maxTestedLength: targetString.length,
        inconclusive: false,
        explanation:
          `Ambiguity Proven! String "${targetString}" produces at least two structurally distinct parse trees ` +
          `(and corresponding distinct leftmost derivations). The derivations diverge at step ${divIdx + 1}.`,
        undecidabilityDisclaimer: UNDECIDABILITY_DISCLAIMER,
      }
    }

    if (trees.length === 1) {
      return {
        isAmbiguous: false,
        evaluatedString: targetString,
        testedStringsCount: 1,
        maxTestedLength: targetString.length,
        inconclusive: true,
        explanation:
          `String "${targetString}" has exactly one parse tree in this grammar. ` +
          `While this string is not ambiguous, the overall grammar may still be ambiguous for other strings.`,
        undecidabilityDisclaimer: UNDECIDABILITY_DISCLAIMER,
      }
    }

    return {
      isAmbiguous: false,
      evaluatedString: targetString,
      testedStringsCount: 1,
      maxTestedLength: targetString.length,
      inconclusive: true,
      explanation: `String "${targetString}" is not in the language generated by this grammar (0 parse trees found).`,
      undecidabilityDisclaimer: UNDECIDABILITY_DISCLAIMER,
    }
  }

  // Case B: Bounded search across strings in Σ*
  let testedCount = 0
  const candidateTerms = grammar.terminals.length > 0 ? grammar.terminals : ['0', '1']

  for (const str of generateStringsUpToLength(candidateTerms, maxLen)) {
    testedCount++
    const trees = findAllParseTrees(grammar, str, 2)

    if (trees.length >= 2) {
      const d1 = treeToLeftmostDerivation(trees[0], grammar.start)
      const d2 = treeToLeftmostDerivation(trees[1], grammar.start)
      const divIdx = findDivergenceStep(d1, d2)

      const witness: AmbiguityWitness = {
        string: str === '' ? 'ε' : str,
        tree1: trees[0],
        tree2: trees[1],
        derivation1: d1,
        derivation2: d2,
        divergenceStepIndex: divIdx,
      }

      return {
        isAmbiguous: true,
        evaluatedString: str === '' ? 'ε' : str,
        witness,
        testedStringsCount: testedCount,
        maxTestedLength: maxLen,
        inconclusive: false,
        explanation:
          `Ambiguity Witness Discovered! The string "${str === '' ? 'ε' : str}" produces 2 distinct parse trees. ` +
          `The two leftmost derivations diverge at step ${divIdx + 1}.`,
        undecidabilityDisclaimer: UNDECIDABILITY_DISCLAIMER,
      }
    }

    if (testedCount > 150) break
  }

  // Search inconclusive up to tested bound
  return {
    isAmbiguous: false,
    testedStringsCount: testedCount,
    maxTestedLength: maxLen,
    inconclusive: true,
    explanation:
      `Inconclusive (No ambiguity found for ${testedCount} tested strings up to length ${maxLen}). ` +
      `No string generated multiple parse trees within the tested bound.`,
    undecidabilityDisclaimer: UNDECIDABILITY_DISCLAIMER,
  }
}

